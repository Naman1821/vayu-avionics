#!/usr/bin/env python3
"""
power_budget.py - power, thermal and battery budget for one Vayu mission.

A hand calculation, independent of the simulator, then compared with what the
simulator measured. Writes docs/POWER_BUDGET.md and docs/img/power_budget.png.

All currents are typical datasheet figures rounded up; check them on the bench.
"""
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# ---- loads (mA, typical) ------------------------------------------------------
LOADS_3V3 = [
    ("STM32F405 at 168 MHz (only used peripherals clocked)", 45.0),
    ("SN65HVD230 CAN transceiver", 10.0),
    ("W25Q128 flash (10 page programs/s, otherwise idle)", 0.5),
    ("ICM-42688-P IMU, 6-axis low-noise mode", 0.9),
    ("MS5611 barometer, 50 conversions/s at OSR 4096", 0.6),
    ("INA226 power monitor", 0.3),
    ("LED, pull-ups, margin", 7.7),
]
LOADS_5V = [
    ("u-blox M8 GPS module (tracking)", 30.0),
    ("433 MHz telemetry modem (RX + 2 Hz TX bursts, average)", 45.0),
]
BUCK_EFF = 0.88          # battery -> 5 V
V_BAT_NOM = 7.4          # 2S Li-ion, nominal under load

# ---- thermal model (same constants as sim/world.h) ---------------------------
BOX_C = 200.0            # J/K: board + 2 x 18650 + enclosure
R_INS = 10.0             # K/W: 12 mm foam around a 10 x 10 x 5 cm box
AREA = 0.04              # m^2
H0 = 30.0                # W/m^2K forced convection at sea level
HEATER_OHMS = 11.0
T_SET = 2.5              # middle of the 0..5 C thermostat band
T_MIN_PARTS = -40.0

# ---- battery ------------------------------------------------------------------
CELL_AH, CELLS = 3.0, 2  # 2S1P 18650
COLD_FACTOR_0C = 0.90    # capacity a Li-ion cell gives at ~0 C (the box is held there)
AGEING = 0.80            # end-of-life capacity
USABLE_DOD = 0.93        # we stop at 3.3 V/cell (LOW state), not at 3.0 V

# ---- mission (same as sim/world.c) -----------------------------------------------
GROUND_M, TOP_M = 5486.4, 15240.0


def isa(h):
    """temperature (C), pressure (Pa), density (kg/m^3) of the standard atmosphere"""
    if h < 11000:
        t = 288.15 - 0.0065 * h
        p = 101325 * (t / 288.15) ** 5.25588
    else:
        t = 216.65
        p = 22632.06 * math.exp(-(h - 11000) * 9.80665 / (287.053 * t))
    return t - 273.15, p, p / (287.053 * t)


def r_total(h):
    """K/W from the box to the outside air: insulation + convection that weakens in thin air"""
    rho = isa(h)[2]
    return R_INS + 1.0 / (H0 * (rho / 1.225) ** 0.6 * AREA)


def heater_needed(h, p_elec):
    t_amb = isa(h)[0]
    return max(0.0, (T_SET - t_amb) / r_total(h) - p_elec)


def main():
    i3 = sum(ma for _, ma in LOADS_3V3) / 1000
    i5 = sum(ma for _, ma in LOADS_5V) / 1000 + i3          # the 3.3 V LDO feeds from 5 V
    p5 = 5.0 * i5
    p_elec = p5 / BUCK_EFF                                    # at the battery
    ldo_loss = (5.0 - 3.3) * i3
    buck_loss = p5 * (1 / BUCK_EFF - 1)

    phases = [  # (name, duration s, altitude for the thermal estimate: average over the phase)
        ("Ground, 18,000 ft", 300 + 180, [GROUND_M]),
        ("Climb, 5 m/s", 1960.7, [GROUND_M + (TOP_M - GROUND_M) * k / 20 for k in range(21)]),
        ("Loiter, 50,000 ft", 3600, [TOP_M]),
        ("Descent, 8 m/s", 1229.2, [GROUND_M + (TOP_M - GROUND_M) * k / 20 for k in range(21)]),
    ]
    rows, e_elec, e_heat = [], 0.0, 0.0
    for name, dur, alts in phases:
        ph = sum(heater_needed(a, p_elec) for a in alts) / len(alts)
        ee, eh = p_elec * dur / 3600, ph * dur / 3600
        e_elec += ee
        e_heat += eh
        rows.append((name, dur / 60, ph, ee, eh))
    warmup = BOX_C * (T_SET - isa(GROUND_M)[0]) / 3600       # cold-soaked box up to 2.5 C
    e_heat += warmup
    total = e_elec + e_heat

    pack_wh = CELLS * 3.6 * CELL_AH
    usable = pack_wh * COLD_FACTOR_0C * AGEING * USABLE_DOD
    margin = usable / total
    cruise_power = p_elec + heater_needed(TOP_M, p_elec)
    endurance_h = usable / cruise_power

    t_noheat = isa(TOP_M)[0] + p_elec * r_total(TOP_M)
    heater_at_low = 6.6 ** 2 / HEATER_OHMS
    heater_at_nom = V_BAT_NOM ** 2 / HEATER_OHMS
    need_cruise = heater_needed(TOP_M, p_elec)

    sim = ROOT / "out" / "nominal" / "truth.csv"
    sim_line = ""
    if sim.exists():
        last = sim.read_text().strip().splitlines()[-1].split(",")
        sim_total, sim_heat = float(last[10]), float(last[11])
        sim_line = (f"| Simulator, nominal flight (measured) | {sim_total - sim_heat:.2f} | {sim_heat:.2f} | "
                    f"**{sim_total:.2f}** |")
        diff = abs(sim_total - total) / sim_total
        if diff > 0.25:
            print(f"budget and simulator disagree by {100 * diff:.0f} %", file=sys.stderr)

    md = [
        "# Power and thermal budget",
        "",
        "Generated by `make budget` (tools/power_budget.py). A hand calculation for the 2-hour",
        "reference mission, independent of the simulator, then checked against it. Currents are",
        "typical datasheet values, rounded up: **measure them on the bench before trusting them.**",
        "",
        "## Electrical load",
        "",
        "| Rail | Part | mA |",
        "|---|---|---:|",
    ]
    md += [f"| 3.3 V (LDO from 5 V) | {n} | {ma:.1f} |" for n, ma in LOADS_3V3]
    md += [f"| 5 V (buck from battery) | {n} | {ma:.1f} |" for n, ma in LOADS_5V]
    md += [
        "",
        f"* 3.3 V rail: **{1000 * i3:.0f} mA**. The LDO burns (5 - 3.3) V x {1000 * i3:.0f} mA = "
        f"**{1000 * ldo_loss:.0f} mW** - fine at this current; a second buck would only pay off above ~200 mA.",
        f"* 5 V rail including the LDO: **{1000 * i5:.0f} mA = {p5:.2f} W**.",
        f"* From the battery through an {100 * BUCK_EFF:.0f} % buck: **{p_elec:.2f} W** "
        f"({1000 * p_elec / V_BAT_NOM:.0f} mA at {V_BAT_NOM} V). Buck loss {1000 * buck_loss:.0f} mW.",
        "",
        "## Thermal",
        "",
        "The box is one thermal mass: 12 mm of foam, then convection to the outside air. Thin air",
        "carries less heat away (convection ~ density^0.6), but at -56.5 C the air is so cold that",
        "the box still loses heat fast.",
        "",
        "| | 18,000 ft (launch) | 50,000 ft (loiter) |",
        "|---|---:|---:|",
        f"| Outside air | {isa(GROUND_M)[0]:.1f} C | {isa(TOP_M)[0]:.1f} C |",
        f"| Air density | {isa(GROUND_M)[2]:.3f} kg/m^3 | {isa(TOP_M)[2]:.3f} kg/m^3 |",
        f"| Box-to-air resistance | {r_total(GROUND_M):.1f} K/W | {r_total(TOP_M):.1f} K/W |",
        f"| Heater power to hold +{T_SET} C | {heater_needed(GROUND_M, p_elec):.2f} W | {need_cruise:.2f} W |",
        "",
        f"* **Without a heater** the box settles at {isa(TOP_M)[0]:.1f} + {p_elec:.2f} W x "
        f"{r_total(TOP_M):.1f} K/W = **{t_noheat:.1f} C**, below the -40 C rating of the parts "
        f"(the simulator's `no_heater` flight reaches -43.5 C).",
        f"* **Heater sizing:** an {HEATER_OHMS:.0f} ohm film gives {heater_at_nom:.1f} W at {V_BAT_NOM} V and "
        f"{heater_at_low:.1f} W at the 6.6 V LOW threshold, against {need_cruise:.1f} W needed at 50,000 ft. "
        "So it can hold 0 C all the way down to LOW; below that the firmware deliberately lets the box "
        "cool to -20 C to save the battery.",
        f"* **Hot spots:** the LDO dissipates {1000 * ldo_loss:.0f} mW (about +22 C in a SOT-23-5 at "
        "~200 K/W), the buck ~0.1 W. With the box at 0..5 C that leaves a large margin to the 85 C rating.",
        "",
        "## Mission energy",
        "",
        "| Phase | Minutes | Heater W | Electronics Wh | Heater Wh |",
        "|---|---:|---:|---:|---:|",
    ]
    md += [f"| {n} | {m:.0f} | {ph:.2f} | {ee:.2f} | {eh:.2f} |" for n, m, ph, ee, eh in rows]
    md += [
        f"| Warm-up of the cold-soaked box (-20.7 to +2.5 C) | | | | {warmup:.2f} |",
        "",
        "| | Electronics Wh | Heater Wh | Total Wh |",
        "|---|---:|---:|---:|",
        f"| Budget (this calculation) | {e_elec:.2f} | {e_heat:.2f} | **{total:.2f}** |",
    ]
    if sim_line:
        md.append(sim_line)
    md += [
        "",
        f"The heater is **{100 * e_heat / total:.0f} %** of the energy. At 50,000 ft keeping warm costs more than",
        "everything else on the board combined, which is why the LOW power state throttles it first.",
        "",
        "## Battery",
        "",
        f"2S1P 18650, {CELL_AH} Ah: {pack_wh:.1f} Wh nominal. Usable = {pack_wh:.1f} x {COLD_FACTOR_0C} (cold, box "
        f"held near 0 C) x {AGEING} (end of life) x {USABLE_DOD} (stop at 3.3 V/cell) = **{usable:.1f} Wh**.",
        "",
        f"* Margin for this mission: **{margin:.1f}x** ({usable:.1f} Wh usable vs {total:.1f} Wh needed).",
        f"* Endurance while loitering at 50,000 ft ({cruise_power:.2f} W): **{endurance_h:.1f} hours**.",
        "* The simulator's `low_battery` flight starts at 40 % charge: the firmware goes LOW during the",
        "  loiter, CRITICAL during descent, and still logs all the way to landing.",
        "",
        "![energy by phase](img/power_budget.png)",
        "",
    ]
    (ROOT / "docs" / "POWER_BUDGET.md").write_text("\n".join(md))
    plot(rows, warmup)
    print(f"electronics {p_elec:.2f} W, mission {total:.2f} Wh ({100 * e_heat / total:.0f} % heater), "
          f"usable {usable:.1f} Wh, margin {margin:.1f}x, endurance at 50,000 ft {endurance_h:.1f} h")


def plot(rows, warmup):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    blue, orange = "#2a78d6", "#eb6834"
    surface, ink, ink2, muted, grid, axis = "#fcfcfb", "#0b0b0b", "#52514e", "#898781", "#e1e0d9", "#c3c2b7"
    names = [r[0] for r in rows] + ["Warm-up"]
    elec = [r[3] for r in rows] + [0.0]
    heat = [r[4] for r in rows] + [warmup]
    fig, ax = plt.subplots(figsize=(8, 3.2), facecolor=surface)
    ax.set_facecolor(surface)
    y = list(range(len(names)))[::-1]
    ax.barh(y, elec, height=0.55, color=blue, label="electronics", edgecolor=surface, linewidth=2)
    ax.barh(y, heat, left=elec, height=0.55, color=orange, label="heater", edgecolor=surface, linewidth=2)
    for yi, e, h in zip(y, elec, heat):
        ax.text(e + h + 0.05, yi, f"{e + h:.2f} Wh", va="center", fontsize=8, color=ink2)
    ax.set_yticks(y, names, fontsize=8, color=ink2)
    ax.tick_params(axis="y", length=0)
    ax.tick_params(axis="x", colors=muted, labelsize=8)
    ax.set_xlabel("energy from the battery, Wh", fontsize=9, color=ink2)
    ax.set_title("Where the energy goes on a 2-hour mission to 50,000 ft", loc="left", fontsize=11,
                 fontweight="bold", color=ink)
    ax.grid(axis="x", color=grid, linewidth=0.6)
    ax.set_axisbelow(True)
    for side in ("top", "right", "left"):
        ax.spines[side].set_visible(False)
    ax.spines["bottom"].set_color(axis)
    ax.legend(frameon=False, fontsize=8, loc="lower right")
    ax.set_xlim(0, max(e + h for e, h in zip(elec, heat)) * 1.18)
    (ROOT / "docs" / "img").mkdir(parents=True, exist_ok=True)
    fig.savefig(ROOT / "docs" / "img" / "power_budget.png", dpi=150, bbox_inches="tight", facecolor=surface)
    plt.close(fig)


if __name__ == "__main__":
    main()
